/** 只保留登入名稱的中文部分，例如「陳大文 Chan Tai Man」→「陳大文」 */
export function chineseName(user) {
  const name = (user?.displayName || "").trim();
  return name.replace(/[A-Za-z][A-Za-z.'\- ]*/g, "").replace(/\s+/g, " ").trim() || name || user?.email?.split("@")[0] || "";
}
